def transform(item: ContentItem) -> str:
    """Преобразовать ContentItem в готовый пост в стиле Насти."""
    prompt_template = PROMPTS.get(item.post_format, PROMPTS["morning_insight"])
    prompt = prompt_template.format(
        tov=TOV_DESCRIPTION,
        title=item.title,
        source=item.source,
        summary=item.summary[:600],
        url=item.url,
        hashtag=item.hashtag,
    )

    try:
        response = client.chat.completions.create(
            model="gpt-4.1-mini",
            messages=[
                {
                    "role": "system",
                    "content": "ты — ghostwriter для telegram-канала про бизнес. пишешь только на русском языке в заданном стиле.",
                },
                {"role": "user", "content": prompt},
            ],
            max_tokens=700,
            temperature=0.85,
        )
        text = response.choices[0].message.content.strip()
        logger.info(f"Transformed [{item.post_format}]: {item.title[:50]}...")
        return text
    except Exception as e:
        logger.error(f"Transform failed: {e}")
        return ""
